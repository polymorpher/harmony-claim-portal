-- Off-chain governor vault metadata. The current name is one row per vault.
-- Each signed change is appended and is not revised. `fields` is reserved for
-- later off-chain values; the API does not write it until a field is defined.
-- Runtime grants are in db/ops/grants.sql, applied by setup-roles.sh.
-- The injector swaps public claim tables and does not touch this schema.

BEGIN;

CREATE SCHEMA IF NOT EXISTS vault;

CREATE TABLE IF NOT EXISTS vault.metadata (
  vault_address  char(42) PRIMARY KEY CHECK (vault_address ~ '^0x[0-9a-f]{40}$'),
  name           text NOT NULL CHECK (
                   char_length(name) BETWEEN 1 AND 80
                   AND name !~ '[[:cntrl:]]'
                   AND name = btrim(name)
                 ),
  fields         jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(fields) = 'object'),
  signer         char(42) NOT NULL CHECK (signer ~ '^0x[0-9a-f]{40}$'),
  signature      text NOT NULL CHECK (signature ~ '^0x[0-9a-fA-F]{130}$'),
  issued_at      timestamptz NOT NULL,
  updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS vault.metadata_changes (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vault_address  char(42) NOT NULL CHECK (vault_address ~ '^0x[0-9a-f]{40}$'),
  name           text NOT NULL CHECK (
                   char_length(name) BETWEEN 1 AND 80
                   AND name !~ '[[:cntrl:]]'
                   AND name = btrim(name)
                 ),
  message        text NOT NULL,
  signature      text NOT NULL CHECK (signature ~ '^0x[0-9a-fA-F]{130}$'),
  signer         char(42) NOT NULL CHECK (signer ~ '^0x[0-9a-f]{40}$'),
  issued_at      timestamptz NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (signature)
);

CREATE INDEX IF NOT EXISTS metadata_changes_vault_idx
  ON vault.metadata_changes (vault_address, issued_at DESC);

INSERT INTO schema_migrations (version) VALUES ('011_vault_metadata')
ON CONFLICT (version) DO NOTHING;

COMMIT;
